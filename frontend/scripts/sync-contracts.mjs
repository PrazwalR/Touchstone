// Copies what a frontend needs from the contracts workspace into frontend/:
//   frontend/abi/<Contract>.json and .ts        ABIs from contracts/out (run `forge build` first)
//   frontend/deployments/<chain>.json and .ts   live addresses, pool and chain metadata, from
//                                               contracts/deployments/<chain>.json and contracts/script/config/<chain>.json
// Run from the repository root after any contract change or deployment: node frontend/scripts/sync-contracts.mjs
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const frontend = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = join(frontend, "..", "contracts");
const CONTRACTS = ["TouchstoneHook", "Settler", "RebateLedger", "TouchstoneFactory", "GuardedRouter", "NyseCalendar", "LicenceAuction", "TouchstoneLens", "IALFHook"];
const camel = (s) => s[0].toLowerCase() + s.slice(1);
const deployBlock = (chainId) => {
  const run = join(contracts, "broadcast", "DeployCore.s.sol", String(chainId), "run-latest.json");
  if (!existsSync(run)) return undefined;
  const blocks = JSON.parse(readFileSync(run, "utf8")).receipts.map((r) => Number.parseInt(r.blockNumber, 16));
  return blocks.length ? Math.min(...blocks) : undefined;
};
const header = "// Generated by frontend/scripts/sync-contracts.mjs; do not edit.\n";

const abiDir = join(frontend, "abi");
mkdirSync(abiDir, { recursive: true });
const index = [];
for (const name of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(join(contracts, "out", `${name}.sol`, `${name}.json`), "utf8"));
  writeFileSync(join(abiDir, `${name}.json`), `${JSON.stringify(artifact.abi, null, 2)}\n`);
  writeFileSync(join(abiDir, `${name}.ts`), `${header}export const ${camel(name)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`);
  index.push(`export { ${camel(name)}Abi } from "./${name}.ts";`);
}
writeFileSync(join(abiDir, "index.ts"), `${header}${index.join("\n")}\n`);

const depDir = join(frontend, "deployments");
mkdirSync(depDir, { recursive: true });
const chains = [];
for (const file of readdirSync(join(contracts, "deployments")).filter((f) => f.endsWith(".json"))) {
  const chain = file.replace(/\.json$/, "");
  const configPath = join(contracts, "script", "config", `${chain}.json`);
  if (!existsSync(configPath)) continue;
  const dep = JSON.parse(readFileSync(join(contracts, "deployments", file), "utf8"));
  const cfg = JSON.parse(readFileSync(configPath, "utf8"));
  const previous = existsSync(join(depDir, file)) ? JSON.parse(readFileSync(join(depDir, file), "utf8")) : {};
  const out = {
    chain,
    chainId: cfg.chainId,
    name: cfg.name,
    explorer: cfg.explorer,
    publicRpc: cfg.publicRpc,
    // First block a reader needs for this deployment's logs. The broadcast folder is not committed, so a
    // fresh checkout keeps the value synced before.
    deployBlock: deployBlock(cfg.chainId) ?? previous.deployBlock ?? null,
    contracts: {
      hook: dep.hook,
      settler: dep.settler,
      ledger: dep.ledger,
      factory: dep.factory,
      guardedRouter: dep.guardedRouter,
      nyseCalendar: dep.nyseCalendar ?? null,
      // Deployments made before M9 have no auction.
      licenceAuction: dep.licenceAuction ?? null,
      // Deployments made before M10 have no lens.
      lens: dep.lens ?? null,
    },
    uniswap: {
      poolManager: cfg.poolManager,
      stateView: cfg.stateView,
      quoter: cfg.quoter,
      poolSwapTest: cfg.routers?.poolSwapTest ?? null,
    },
    oracles: {
      pyth: cfg.pyth,
      chainlinkEthUsd: cfg.referenceFeed,
      pythEthUsdId: cfg.basePriceId,
      pythUsdcUsdId: cfg.quotePriceId,
    },
    tokens: { risky: { symbol: "ETH", address: cfg.pool?.risky, decimals: 18 }, quote: { symbol: "USDC", address: cfg.pool?.quote, decimals: 6 } },
    // Price and liquidity at creation only; read live values from StateView.
    pools: dep.pool
      ? [
          {
            label: "ETH / USDC",
            poolId: dep.pool.poolId,
            currency0: dep.pool.currency0,
            currency1: dep.pool.currency1,
            fee: dep.pool.fee,
            tickSpacing: dep.pool.tickSpacing,
            hooks: dep.hook,
            initialSqrtPriceX96: dep.pool.sqrtPriceX96,
            initialLiquidity: dep.pool.liquidity,
          },
        ]
      : [],
  };
  writeFileSync(join(depDir, `${chain}.json`), `${JSON.stringify(out, null, 2)}\n`);
  chains.push(chain);
}
const ident = (c) => camel(c.replace(/-([a-z])/g, (_, l) => l.toUpperCase()));
writeFileSync(
  join(depDir, "index.ts"),
  `${header}${chains.map((c) => `import ${ident(c)} from "./${c}.json" with { type: "json" };`).join("\n")}\n\nexport const deployments = { ${chains.map((c) => `"${c}": ${ident(c)}`).join(", ")} } as const;\n`,
);
process.stdout.write(`synced ${CONTRACTS.length} ABIs and ${chains.length} deployment(s) into ${frontend}\n`);
