// Copies the ABIs the off-chain services need from contracts/out into shared/abi as TypeScript
// modules, so viem infers event and function types, and as plain JSON for the frontend or any other client.
// Run after `forge build`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "..", "..", "contracts", "out");
const dest = join(here, "..", "abi");
const contracts = [
  "TouchstoneHook",
  "Settler",
  "RebateLedger",
  "TouchstoneFactory",
  "GuardedRouter",
  "NyseCalendar",
  "LicenceAuction",
  "TouchstoneLens",
  // URC-4: the hook serves these through its fallback, so they are not in the hook's own ABI.
  "IALFHook",
];

mkdirSync(dest, { recursive: true });
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8"));
  const body = `// Generated by shared/scripts/export-abi.mjs from contracts/out; do not edit.\nexport const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(dest, `${name}.ts`), body);
  writeFileSync(join(dest, `${name}.json`), `${JSON.stringify(artifact.abi, null, 2)}\n`);
}
process.stdout.write(`exported ${contracts.length} ABIs to ${dest}\n`);
